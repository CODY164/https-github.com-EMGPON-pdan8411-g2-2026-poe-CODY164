import os, glob, time, hashlib, io, random, warnings
warnings.filterwarnings("ignore")
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"
import numpy as np, requests, matplotlib.pyplot as plt
from PIL import Image
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
from sklearn.model_selection import train_test_split
from sklearn.utils.class_weight import compute_class_weight
from sklearn.metrics import classification_report, confusion_matrix, ConfusionMatrixDisplay

SEED = 42
random.seed(SEED); np.random.seed(SEED); tf.random.set_seed(SEED)

SERPAPI_KEY      = SERPAPI_KEY or os.environ.get("SERPAPI_KEY", "")
BONUS_IMAGES     = 18                                   # reserved for the Step 8 bonus test
